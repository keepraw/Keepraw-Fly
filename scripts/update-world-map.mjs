import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { geoGraticule, geoNaturalEarth1, geoPath } from "d3-geo";

const NATURAL_EARTH_VERSION = "5.1.2";
const D3_GEO_VERSION = "3.1.1";
const D3_ARRAY_VERSION = "3.2.4";
const INTERNMAP_VERSION = "2.0.3";
const NATURAL_EARTH_ROOT = `https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v${NATURAL_EARTH_VERSION}`;
const LAND_URL = `${NATURAL_EARTH_ROOT}/geojson/ne_110m_land.geojson`;
const NATURAL_EARTH_LICENSE_URL = `${NATURAL_EARTH_ROOT}/LICENSE.md`;
const D3_GEO_LICENSE_URL = `https://raw.githubusercontent.com/d3/d3-geo/v${D3_GEO_VERSION}/LICENSE`;
const D3_ARRAY_LICENSE_URL = `https://raw.githubusercontent.com/d3/d3-array/v${D3_ARRAY_VERSION}/LICENSE`;
const INTERNMAP_LICENSE_URL = `https://raw.githubusercontent.com/mbostock/internmap/v${INTERNMAP_VERSION}/LICENSE`;
const OUTPUT_DIRECTORY = fileURLToPath(new URL("../apps/web/src/data/", import.meta.url));
const WORLD_WIDTH = 960;
const WORLD_HEIGHT = 480;

const [landText, naturalEarthLicense, d3GeoLicense, d3ArrayLicense, internmapLicense] = await Promise.all([
  fetchText(LAND_URL),
  fetchText(NATURAL_EARTH_LICENSE_URL),
  fetchText(D3_GEO_LICENSE_URL),
  fetchText(D3_ARRAY_LICENSE_URL),
  fetchText(INTERNMAP_LICENSE_URL),
]);
const land = JSON.parse(landText);
const sphere = { type: "Sphere" };
const graticule = geoGraticule().step([30, 30])();
const projection = geoNaturalEarth1()
  .fitExtent([[16, 16], [WORLD_WIDTH - 16, WORLD_HEIGHT - 16]], sphere)
  .precision(0.25);
const path = geoPath(projection).digits(1);
const landPath = requiredPath(path(land), "land");
const spherePath = requiredPath(path(sphere), "sphere");
const graticulePath = requiredPath(path(graticule), "graticule");
const scale = projection.scale();
const translate = projection.translate();

const generatedModule = `// Generated by scripts/update-world-map.mjs. Do not edit by hand.\n` +
  `export const WORLD_WIDTH = ${WORLD_WIDTH};\n` +
  `export const WORLD_HEIGHT = ${WORLD_HEIGHT};\n` +
  `export const MAP_PROJECTION_SCALE = ${scale.toFixed(6)};\n` +
  `export const MAP_PROJECTION_TRANSLATE = [${translate[0].toFixed(6)}, ${translate[1].toFixed(6)}] as const;\n` +
  `export const WORLD_SPHERE_PATH = ${JSON.stringify(spherePath)};\n` +
  `export const WORLD_GRATICULE_PATH = ${JSON.stringify(graticulePath)};\n` +
  `export const WORLD_LAND_PATH = ${JSON.stringify(landPath)};\n`;
const sourceMetadata = {
  naturalEarth: {
    version: NATURAL_EARTH_VERSION,
    scale: "1:110m",
    dataset: "Natural Earth Vector land polygons",
    source: LAND_URL,
    sha256: sha256(landText),
    license: "Public domain; see LICENSE.natural-earth",
  },
  d3Geo: {
    version: D3_GEO_VERSION,
    source: `https://github.com/d3/d3-geo/tree/v${D3_GEO_VERSION}`,
    license: "ISC; see LICENSE.d3-geo",
    bundledDependencies: [
      { name: "d3-array", version: D3_ARRAY_VERSION, license: "ISC; see LICENSE.d3-array" },
      { name: "internmap", version: INTERNMAP_VERSION, license: "ISC; see LICENSE.internmap" },
    ],
  },
  projection: "Natural Earth 1",
  generatedArtifacts: ["WORLD_SPHERE_PATH", "WORLD_GRATICULE_PATH", "WORLD_LAND_PATH"],
};

await mkdir(OUTPUT_DIRECTORY, { recursive: true });
await Promise.all([
  writeFile(`${OUTPUT_DIRECTORY}/world-map.generated.ts`, generatedModule, "utf8"),
  writeFile(`${OUTPUT_DIRECTORY}/world-map.source.json`, `${JSON.stringify(sourceMetadata, null, 2)}\n`, "utf8"),
  writeFile(`${OUTPUT_DIRECTORY}/LICENSE.natural-earth`, normalizeEndings(naturalEarthLicense), "utf8"),
  writeFile(`${OUTPUT_DIRECTORY}/LICENSE.d3-geo`, normalizeEndings(d3GeoLicense), "utf8"),
  writeFile(`${OUTPUT_DIRECTORY}/LICENSE.d3-array`, normalizeEndings(d3ArrayLicense), "utf8"),
  writeFile(`${OUTPUT_DIRECTORY}/LICENSE.internmap`, normalizeEndings(internmapLicense), "utf8"),
]);

console.log(`Generated Natural Earth ${NATURAL_EARTH_VERSION} SVG paths using d3-geo ${D3_GEO_VERSION}.`);

async function fetchText(url) {
  const response = await fetch(url, { headers: { "user-agent": "keepraw-fly-map-generator" } });
  if (!response.ok) throw new Error(`Unable to download ${url}: ${response.status} ${response.statusText}`);
  return response.text();
}

function requiredPath(value, label) {
  if (!value) throw new Error(`d3-geo did not generate the ${label} SVG path.`);
  return value;
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function normalizeEndings(value) {
  return `${value.replace(/\r\n/g, "\n").trimEnd()}\n`;
}
