import { access, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageRoot = resolve(repositoryRoot, "apps/web/node_modules/soaring-symbols/dist");
const outputPath = resolve(repositoryRoot, "apps/web/src/generated/airline-icons.ts");
const airlines = JSON.parse(await readFile(resolve(packageRoot, "airlines.json"), "utf8"));
const airlineAssets = [];

for (const airline of airlines) {
  for (const filename of ["icon.svg", "icon-mono.svg", "logo.svg", "logo-mono.svg"]) {
    try {
      await access(resolve(packageRoot, "assets", airline.slug, filename));
      airlineAssets.push({
        ...airline,
        filename,
        variant: filename.startsWith("icon") ? "icon" : "logo",
      });
      break;
    } catch {
      // Continue through the preferred square-icon and logo variants.
    }
  }
}

airlineAssets.sort((left, right) => left.slug.localeCompare(right.slug, "en"));

const imports = airlineAssets.map(
  (airline, index) => `import asset${index} from "soaring-symbols/assets/${airline.slug}/${airline.filename}?url";`,
);
const codeEntries = new Map();

airlineAssets.forEach((airline, index) => {
  for (const code of [airline.iata, airline.icao]) {
    if (!code) continue;
    const normalizedCode = String(code).toUpperCase();
    const existing = codeEntries.get(normalizedCode);
    if (existing !== undefined && existing !== index) {
      throw new Error(`Duplicate airline designator ${normalizedCode} in soaring-symbols`);
    }
    codeEntries.set(normalizedCode, index);
  }
});

const mappings = [...codeEntries.entries()]
  .sort(([left], [right]) => left.localeCompare(right, "en"))
  .map(([code, index]) => {
    const asset = airlineAssets[index];
    return `  ${JSON.stringify(code)}: { src: asset${index}, variant: ${JSON.stringify(asset.variant)} },`;
  });

const source = `// Generated by scripts/generate-airline-icons.mjs. Do not edit manually.\n${imports.join("\n")}\n\nexport interface AirlineLogoAsset {\n  src: string;\n  variant: "icon" | "logo";\n}\n\nexport const airlineLogoByCode: Readonly<Record<string, AirlineLogoAsset>> = Object.freeze({\n${mappings.join("\n")}\n});\n`;

await writeFile(outputPath, source, "utf8");
console.log(`Generated ${airlineAssets.length} airline SVG assets and ${codeEntries.size} designator mappings.`);
