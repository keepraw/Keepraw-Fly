// Builds the precompiled (standalone) Ajv validator for the keepraw-fly schema.
// Runtime schema compilation uses Function(), which a strict Content Security
// Policy without 'unsafe-eval' forbids, so the application ships generated code.
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const schemaPath = fileURLToPath(
  new URL("../../schema/keepraw-fly.schema.json", import.meta.url),
);

const requireReplacements = new Map([
  ['require("ajv-formats/dist/formats")', "ajvFormats"],
  ['require("ajv/dist/runtime/ucs2length")', "ajvUcs2length"],
]);

export function generateSchemaValidatorSource() {
  const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
  // Options must match the former runtime compiler exactly.
  const ajv = new Ajv2020.default({
    allErrors: true,
    strict: true,
    code: { source: true, esm: true, lines: true },
  });
  addFormats.default(ajv);
  const validate = ajv.compile(schema);
  let code = standaloneCode.default(ajv, validate);
  for (const [call, identifier] of requireReplacements)
    code = code.replaceAll(call, identifier);
  const unresolved = code.match(/require\([^)]*\)/g);
  if (unresolved)
    throw new Error(
      `Unhandled standalone dependency: ${unresolved.join(", ")}`,
    );
  if (/\b(?:new\s+)?Function\s*\(|\beval\s*\(/.test(code))
    throw new Error("Generated validator must not evaluate code at runtime");
  return [
    "// GENERATED by packages/validator/scripts/generate-schema-validator.mjs.",
    "// Do not edit. Regenerate after changing packages/schema/keepraw-fly.schema.json.",
    "/* eslint-disable */",
    "// @ts-nocheck",
    'import { fullFormats } from "ajv-formats/dist/formats.js";',
    'import ucs2length from "../ucs2length.js";',
    "const ajvFormats = { fullFormats };",
    "const ajvUcs2length = { default: ucs2length };",
    code,
    "",
  ].join("\n");
}
